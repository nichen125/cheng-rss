-- 0005：简报的引用表与「值得一读」
--
-- 为什么必须单独存一列（而不是继续从 body_md 里正则反查簇 id）：
--
-- 3.3 的 `renderCitations` 在**落库前**就把 `{{cite:cl_xxx}}` 换成了 `[1]`，
-- 所以 body_md 里根本没有簇 id。而 3.4 的 `GET /digests/:id` 一直在用
-- `/\{\{cite:([A-Za-z0-9_-]+)\}\}/g` 去匹配它 —— 那个正则永远匹配不到，
-- `clusters` 恒为空数组。接口返回 200、页面不报错，只是 `[1]` 点了没反应。
--
-- 这是"两半都对但接不上"的典型：3.3 的渲染对、3.4 的路由对，中间少了
-- 「把引用表存下来」这一个动作。
--
-- 存成 JSON 数组而不是单独一张表：
--   · 引用表是**这份简报的快照**，不该跟着簇的生命周期变化
--     （簇整窗重算时会被删，而简报要保留它当时的引用文字）
--   · 一份简报最多 12 条引用，没有按引用反查的需求
--   · 因此标题也一并存下来 —— 簇被清理后脚注仍然有文字，
--     不会变成一排 "1. 2. 3." 的空号

ALTER TABLE digests ADD COLUMN cites TEXT;

-- worth_reading 是模型给的「低热度但值得一读」的事件 id 列表。
-- 3.3 一直没落库 —— 它在 `DigestBodySchema` 里、m3-03 也断言了模型会填，
-- 但保存时被丢掉了。§15.4 的页面第三块「值得一读」因此没有数据来源。
ALTER TABLE digests ADD COLUMN worth_reading TEXT;
